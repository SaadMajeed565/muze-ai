/**
 * Tool inventory report, generated from the registry (Phase 3).
 *
 * Usage: node scripts/tool-inventory.mjs
 * Output: TOOL-INVENTORY.md in the repo root (generated; do not hand-edit).
 *
 * It bundles the extension's tool-contracts with esbuild (the project's
 * existing bundler), runs the bundle to dump the registry as JSON, and
 * renders the report from that dump — so every count, tag, risk, and
 * deprecation status comes from the code, never from a hand-written
 * number. Run it after any registry change; the coordinator's docs pass
 * should use its counts, not stale hand-written ones.
 */
import { spawnSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entryDir = await mkdtemp(join(tmpdir(), "muze-inventory-"));
const entry = join(entryDir, "entry.ts");
const bundle = join(entryDir, "bundle.cjs");
try {
  await writeFile(
    entry,
    `import { TOOL_SCHEMAS, UNIFIED_ACTION_RISK } from ${JSON.stringify(join(root, "extension/libs/tool-contracts/toolset.ts"))};\n` +
      `import { toToolDescriptor } from ${JSON.stringify(join(root, "extension/libs/tool-contracts/tools.ts"))};\n` +
      `import { TOOL_META, deprecatedUnifiedAction } from ${JSON.stringify(join(root, "extension/libs/tool-contracts/tool-meta.ts"))};\n` +
      `const tools = TOOL_SCHEMAS.map((t) => toToolDescriptor(t));\n` +
      `const actions = UNIFIED_ACTION_RISK.map((e) => ({ ...e, deprecated: deprecatedUnifiedAction(e.unifiedTool, e.action, e.domain) }));\n` +
      `console.log(JSON.stringify({ tools, actions, meta: TOOL_META }));\n`,
  );
  const esbuildBin = join(root, "extension/node_modules/.bin/esbuild");
  const built = spawnSync(esbuildBin, [entry, "--bundle", "--platform=node", "--format=cjs", `--outfile=${bundle}`], { encoding: "utf8" });
  if (built.status !== 0) {
    console.error(built.stdout, built.stderr);
    throw new Error("esbuild failed to bundle the registry for the inventory report");
  }
  const run = spawnSync(process.execPath, [bundle], { encoding: "utf8" });
  if (run.status !== 0) {
    console.error(run.stdout, run.stderr);
    throw new Error("inventory bundle failed to run");
  }
  const { tools, actions, meta } = JSON.parse(run.stdout);

  const granular = tools.filter((t) => !t.name.includes(".") || !["browser", "tabs", "windows", "navigate", "observe", "act", "wait", "form", "submit", "devtools", "data", "clipboard", "files"].includes(t.name));
  const unifiedNames = new Set(["browser", "tabs", "windows", "navigate", "observe", "act", "wait", "form", "submit", "devtools", "data", "clipboard", "files"]);
  const unified = tools.filter((t) => unifiedNames.has(t.name));
  const tasks = tools.filter((t) => t.name.startsWith("tasks."));
  const metaTools = tools.filter((t) => t.name.startsWith("tools."));
  const granularOnly = tools.filter((t) => !unifiedNames.has(t.name) && !t.name.startsWith("tasks.") && !t.name.startsWith("tools."));
  const byCategory = {};
  const byRisk = {};
  for (const t of tools) {
    byCategory[t.category] = (byCategory[t.category] ?? 0) + 1;
    byRisk[t.risk] = (byRisk[t.risk] ?? 0) + 1;
  }
  const missingMeta = tools.filter((t) => !meta[t.name] || !meta[t.name].tags || meta[t.name].tags.length === 0).map((t) => t.name);
  // tools.batch / tools.discover are real MCP meta tools served by a
  // fallback descriptor in the gateway, not registry tools in TOOL_SCHEMAS;
  // their metadata is expected and is the only allowed extra.
  const META_ONLY = new Set(["tools.batch", "tools.discover"]);
  const extraMeta = Object.keys(meta).filter((n) => !tools.some((t) => t.name === n) && !META_ONLY.has(n));
  const deprecatedActions = actions.filter((a) => a.deprecated);
  const core = ["observe", "act", "navigate", "form", "data", "tools.batch", "tools.discover", "tasks.create", "tasks.get", "tasks.list", "tasks.pause", "tasks.resume", "tasks.cancel"];
  const deprecatedInCore = core.filter((n) => tools.find((t) => t.name === n)?.deprecated);

  const lines = [];
  lines.push("# Muze AI — Tool inventory (generated)");
  lines.push("");
  lines.push("> Generated by `node scripts/tool-inventory.mjs` from the registry. Do not hand-edit; re-run the script after any registry change.");
  lines.push("");
  lines.push(`- Total tools: **${tools.length}** (${granularOnly.length} granular + ${unified.length} unified + ${tasks.length} tasks + ${metaTools.length} meta)`);
  lines.push(`- Unified actions in the per-action risk table: ${actions.length}`);
  lines.push(`- Deprecated unified actions (still working in 2.x, removal in registry 3.0): ${deprecatedActions.length}`);
  lines.push(`- Deprecated tools in the core set: ${deprecatedInCore.length} (must be 0)`);
  lines.push(`- Tools missing tags: ${missingMeta.length} (must be 0)${missingMeta.length ? ` — ${missingMeta.join(", ")}` : ""}`);
  lines.push(`- Metadata entries with no registry tool: ${extraMeta.length} (must be 0)${extraMeta.length ? ` — ${extraMeta.join(", ")}` : ""}`);
  lines.push("");
  lines.push("## By category");
  lines.push("");
  for (const [cat, count] of Object.entries(byCategory).sort()) lines.push(`- ${cat}: ${count}`);
  lines.push("");
  lines.push("## By risk (whole-tool risk; unified tools also have per-action risk below)");
  lines.push("");
  for (const [risk, count] of Object.entries(byRisk).sort()) lines.push(`- ${risk}: ${count}`);
  lines.push("");
  lines.push("## Tools");
  lines.push("");
  lines.push("| Tool | Category | Risk | Approval | Tags | Deprecated |");
  lines.push("| --- | --- | --- | --- | --- | --- |");
  for (const t of [...tools].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`| ${t.name} | ${t.category} | ${t.risk} | ${t.requiresApproval ? "yes" : "no"} | ${(t.tags ?? []).join(", ")} | ${t.deprecated ? `yes, use ${t.useInstead ?? ""}` : "no"} |`);
  }
  lines.push("");
  lines.push("## Unified per-action risk (from action-risk.ts)");
  lines.push("");
  lines.push("| Unified tool | Action | Domain | Granular tool | Risk | Approval | Deprecated (use instead) |");
  lines.push("| --- | --- | --- | --- | --- | --- | --- |");
  for (const a of actions) {
    lines.push(`| ${a.unifiedTool} | ${a.action} | ${a.domain ?? ""} | ${a.granularTool} | ${a.risk} | ${a.requiresApproval === true ? "yes" : a.requiresApproval === "granular" ? "granular" : "no"} | ${a.deprecated ? `yes (${a.deprecated.useInstead})` : "no"} |`);
  }
  lines.push("");
  lines.push("## Deprecation notes (Phase 3)");
  lines.push("");
  lines.push("- navigate tab/window actions: deprecated in 2.x, still working, use tabs.* / windows.* instead. Removal only in registry 3.0 with live-usage evidence (Phase 4 removal guard).");
  lines.push("- data devtools/clipboard domains: deprecated in 2.x, still working, use devtools.* / clipboard.* instead. Removal only in registry 3.0 with live-usage evidence.");
  lines.push("- No tool was removed in this phase, and no deprecated tool is in the core set.");
  lines.push("");

  await writeFile(join(root, "TOOL-INVENTORY.md"), lines.join("\n"));
  console.error(`wrote TOOL-INVENTORY.md: ${tools.length} tools, ${actions.length} unified actions, ${deprecatedActions.length} deprecated actions`);
  if (missingMeta.length || extraMeta.length || deprecatedInCore.length) {
    console.error("inventory checks failed");
    process.exit(1);
  }
} finally {
  await rm(entryDir, { recursive: true, force: true });
}
